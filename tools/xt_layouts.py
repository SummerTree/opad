#!/usr/bin/env python3
"""Regenerates core/src/xt/xt_layouts.inc: how each Parasolid node type's layout changed across schema versions.

Input: the layouts the X_T test's corpus survey harvests from files that embed their own layouts (OPAD_XT_HARVEST, see
tests/test_xt.cpp). Each line there is "<schema version> <node type> | <field:type[n][!]> ... | <files>". For every node
type the versions are walked in order and each change of layout becomes one entry "since <version> the fields are ...";
files without embedded layouts (xt_schema.cpp, schema_for) take the latest entry at or below their own version.

    OPAD_XT_CORPUS=<folder of public .x_t/.x_b> OPAD_XT_HARVEST=harvest.txt build/windows/bin/opad-test-xt
    python tools/xt_layouts.py harvest.txt > core/src/xt/xt_layouts.inc
"""
import collections
import sys


def main():
    seen = collections.defaultdict(dict)  # type -> version -> layout (the most common one if files disagree)
    votes = collections.defaultdict(collections.Counter)
    for line in open(sys.argv[1], encoding="utf-8"):
        head, layout, _files = line.rstrip("\n").split(" | ")
        version, node_type = (int(x) for x in head.split())
        votes[(node_type, version)][layout.strip()] += 1
    for (node_type, version), counter in votes.items():
        seen[node_type][version] = counter.most_common(1)[0][0]
    print("// Generated by tools/xt_layouts.py from layouts embedded in public Parasolid files; do not edit by hand.")
    print("// {node type, since schema version, \"field:type[count][!not transmitted] ...\"}")
    for node_type in sorted(seen):
        last = None
        for version in sorted(seen[node_type]):
            layout = seen[node_type][version]
            if layout != last:
                print(f'{{{node_type}, {version}, "{layout}"}},')
                last = layout


if __name__ == "__main__":
    main()
